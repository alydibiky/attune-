// v9.9.6 N1 (Ali OK'd): "track my cranes: name, tonnage, next inspection" → a table; rows added by talking; dates → reminders
import assert from "node:assert/strict";
import * as T from "../../web-src/tables.js";
let n = 0; const ok = (c, m) => { assert.ok(c, m); n++; console.log("PASS " + m); };
const NOW = Date.parse("2026-11-10T12:00:00");
const p = T.parseTrack("track my cranes: name, tonnage, next inspection");
ok(p && p.name === "Cranes" && p.cols.map((c) => c.type).join() === "text,number,date", "“track my cranes: name, tonnage, next inspection” → Cranes · text, number, date");
ok(T.parseTrack("جدول للعربيات: الاسم، الموديل، تاريخ الترخيص").cols[2].type === "date", "«جدول للعربيات: الاسم، الموديل، تاريخ الترخيص» → a date column");
ok(T.parseTrack("track my mood") === null, "no columns → not a table");
let st = { v: 1, tables: [T.makeTable(p, NOW)] };
const tb = st.tables[0], [cN, cT, cD] = tb.cols;
let r = T.parseRow(st, "add Grove GMK, 100 tons, inspection 4 Dec", NOW);
ok(r && r.cells[cN.id] === "Grove GMK" && r.cells[cT.id] === 100 && r.cells[cD.id] === "2026-12-04", "“add Grove GMK, 100 tons, inspection 4 Dec” → Grove GMK · 100 · 2026-12-04");
st = T.addRow(st, tb.id, r.cells);
r = T.parseRow(st, "add Liebherr LTM, 200, 20 Nov", NOW);
ok(r.cells[cN.id] === "Liebherr LTM" && r.cells[cT.id] === 200 && r.cells[cD.id] === "2026-11-20", "“add Liebherr LTM, 200, 20 Nov” → each value to its kind of column");
st = T.addRow(st, tb.id, r.cells);
r = T.parseRow(st, "ضيف XCMG QY، 50 طن، الفحص ١٢ يناير", NOW);
ok(r.cells[cN.id] === "XCMG QY" && r.cells[cT.id] === 50 && r.cells[cD.id] === "2027-01-12", "«ضيف XCMG QY، 50 طن، الفحص ١٢ يناير» → 12 Jan 2027 (next year)");
st = T.addRow(st, tb.id, r.cells);
ok(T.dateOf("Dec 4", NOW) === "2026-12-04" && T.dateOf("4/12/2026", NOW) === "2026-12-04" && T.dateOf("tomorrow", NOW) === "2026-11-11", "dates: “Dec 4”, “4/12/2026”, “tomorrow”");
const rem = T.dueReminders(st.tables[0], NOW);
ok(rem.length === 3 && rem.find((x) => x.title === "Liebherr LTM — Next inspection").at === Date.parse("2026-11-19T09:00:00"), "a reminder the day before each inspection, 9:00 (Liebherr: 19 Nov)");
ok(Object.keys(T.calendar(st.tables[0])).sort().join() === "2026-11-20,2026-12-04,2027-01-12", "calendar: the three inspection days");
const sp = T.parseTrack("track our clients: name, status, phone");
let st2 = { v: 1, tables: [T.makeTable(sp, NOW)] };
st2 = T.addRow(st2, st2.tables[0].id, T.parseRow(st2, "add Sheikh, waiting, 0100", NOW).cells);
st2 = T.addRow(st2, st2.tables[0].id, T.parseRow(st2, "add Karim, paid, 0111", NOW).cells);
const b = T.board(st2.tables[0]);
ok(b && b.col.name === "Status" && b.groups.map((g) => g.key).sort().join() === "paid,waiting", "board: clients grouped by Status (waiting · paid)");
ok(T.parseRow(st, "add milk", NOW) === null && T.parseRow(st, "add milk to my shopping list", NOW) === null, "with a Cranes table, “add milk” / “add milk to my shopping list” are NOT rows");
ok(T.parseRow({ v: 1, tables: [] }, "add milk", NOW) === null, "no table → “add milk” is not a row (lists keep their job)");
console.log("ALL PASSED v996tables (" + n + " checks)");
