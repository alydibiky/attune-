// v7.8: Tools in two levels (Gemini's Area 6 mock-up) — the tool log and the reports, by code.
import { logTool, loadLog, toolsReport, familyReport, familyOf } from "../../web-src/toollog.js";
let fail = 0; const ok = (c, w) => { console.log((c ? "PASS " : "FAIL ") + w); if (!c) fail++; };
const mem = { d: {}, getItem(k) { return this.d[k] || null; }, setItem(k, v) { this.d[k] = v; } };
const now = new Date("2026-10-24T15:00:00").getTime(), D = 86400000;
ok(familyOf("improve") === "writing" && familyOf("convert") === "files" && familyOf("chat") === null, "tools belong to families; Chat is not a tool");
logTool({ mode: "chat", title: "x" }, { now, store: mem });
ok(loadLog(mem).length === 0, "an unknown tool is not logged");
logTool({ mode: "improve", title: "Compare embedded boards", target: "claude", before: 18, after: 12 }, { now: now - 2 * D, store: mem });
logTool({ mode: "improve", title: "Supplier email", target: "chatgpt", before: 40, after: 20 }, { now: now - D, store: mem });
logTool({ mode: "improve", title: "Old one", target: "claude", before: 10, after: 9 }, { now: now - 9 * D, store: mem });
logTool({ mode: "convert", title: "Lab4.pdf → .docx", kind: "pdf-docx", mb: 1.8, secs: 1.9 }, { now: now - 3600e3, store: mem });
logTool({ mode: "instant", title: "Supplier WhatsApp", kind: "summarise" }, { now: now - 600e3, store: mem });
logTool({ mode: "studio", title: "Nile felucca", kind: "watercolour", secs: 6.2 }, { now: now - 60e3, store: mem });
const L = loadLog(mem);
ok(L.length === 6 && L[0].title === "Nile felucca" && L[0].fam === "studio", "newest first, with its family");
ok(!JSON.stringify(L).includes("text"), "titles and numbers only — never the text");
const r = toolsReport(L, now);
ok(r.week === 5 && r.by.writing === 2 && r.by.files === 1 && r.by.studio === 1 && r.today === 3, "this week by family, and today: " + JSON.stringify(r.by));
ok(r.change === 400 && r.recent.length === 4, "vs the week before (1 → 5), the 4 latest outputs");
const w = familyReport(L, "writing", now);
ok(w.week === 2 && w.wordsSaved === 26 && w.tighter === 45, "Writing: 2 this week, 26 words saved, 45% tighter");
ok(w.targets[0].pct === 50 && w.targets.length === 2, "favourite targets with shares");
const f = familyReport(L, "files", now);
ok(f.mb === 1.8 && f.avgSecs === 1.9, "Files: MB processed and average seconds");
ok(familyReport([], "studio", now).week === 0 && toolsReport([], now).change === null, "nothing yet → empty reports");
for (let i = 0; i < 320; i++) logTool({ mode: "instant", title: "x" + i }, { now: now + i, store: mem });
ok(loadLog(mem).length === 300, "the log keeps the last 300");
console.log(fail ? "FAIL " + fail : "PASS all");
