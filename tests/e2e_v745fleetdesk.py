"""v6.45 Fleet ← Ali's two desktop programs: Today's cash month + 6 months + who owes most + Active now counts; Rates in one
table; Profit per site and Query with Print / Excel; a period expense; extra crane / client / bank fields; the store's
dashboard numbers, Movements filters, a report row's history, the reference-code issues, Lists (rename everywhere); Arabic.
  PYTHONPATH=tests/pwshim:tests python3 tests/e2e_v745fleetdesk.py
"""
from playwright.sync_api import sync_playwright
from harness import Env, new_page, check, real_errors, finish
env = Env(); errors = []
def open_fleet(page, biz="Business"):
    page.goto(env.url); page.wait_for_selector("[data-testid=phone-home]", timeout=15000)
    page.locator("nav button").last.click(); page.wait_for_timeout(300)
    page.locator(".rounded-t-2xl button:has-text('%s')" % biz).first.click()
    page.wait_for_selector("[data-testid=fleet-open]", timeout=8000); page.click("[data-testid=fleet-open]")
    page.wait_for_selector("[data-testid=fleet-app]", timeout=5000)
    page.click("[data-testid=fleet-demo]"); page.wait_for_selector("[data-testid=fleet-today]")
close = lambda page: page.locator("[data-testid=fleet-sheet] button[aria-label]").first.click()
with sync_playwright() as p:
    br = p.chromium.launch()
    ctx, page = new_page(br, env, errors, extra_init="try{localStorage.setItem('attune:start','home')}catch(e){}")
    page.set_viewport_size({"width": 390, "height": 844})
    open_fleet(page)
    # ---- Today
    cash = page.inner_text("[data-testid=fleet-cash]")
    check("Collected" in cash and "Profit, all time" in cash, "Today shows the month on a cash basis and the all-time profit")
    check("2 jobs" in page.inner_text("[data-testid=fleet-active-counts]"), "Active now's counts: 2 jobs")
    page.click("[data-testid=fleet-cash-more]"); page.wait_for_selector("[data-testid=fleet-six]")
    check(page.locator("[data-testid=fleet-six-row]").count() == 6, "the last 6 months, one row each")
    check(page.locator("[data-testid=fleet-owe]").count() >= 1, "who owes most is listed")
    # ---- Rates
    page.click("[data-testid=fleet-menu]"); page.click("[data-testid=fleet-rates-open]"); page.wait_for_selector("[data-testid=fleet-rates]")
    page.locator("[data-testid=fleet-rate-d]").first.fill("33000"); page.click("[data-testid=fleet-save]"); page.wait_for_timeout(300)
    check(page.locator("[data-testid=fleet-rates]").count() == 0, "Rates saved, the sheet closed")
    page.click("[data-testid=fleet-menu]"); page.click("[data-testid=fleet-rates-open]"); page.wait_for_selector("[data-testid=fleet-rates]")
    check(page.locator("[data-testid=fleet-rate-d]").first.input_value() == "33000", "the new daily rate stayed")
    close(page)
    # ---- Money → Profit per site, Query
    page.click("[data-testid=fleet-tab-money]"); page.click("[data-testid=fleet-mseg-sites]"); page.wait_for_selector("[data-testid=fleet-sites]")
    page.click("[data-testid=fleet-srange-all]"); page.wait_for_timeout(150)
    check(page.locator("[data-testid=fleet-sites-table-row]").count() == 2 and "New Capital" in page.inner_text("[data-testid=fleet-sites-table]"), "profit per site: both demo sites")
    page.click("[data-testid=fleet-sites-print]"); page.wait_for_timeout(300)
    page.click("[data-testid=fleet-mseg-query]"); page.wait_for_selector("[data-testid=fleet-query]")
    page.click("[data-testid=fleet-qs-pending]"); page.wait_for_timeout(150)
    n_pending = page.locator("[data-testid=fleet-q-table-row]").count()
    page.click("[data-testid=fleet-qs-cleared]"); page.wait_for_timeout(150)
    check(n_pending == 2 and page.locator("[data-testid=fleet-q-table-row]").count() == 0, "Query: the 2 demo cheques are pending, none cleared")
    page.click("[data-testid=fleet-qt-jobs]"); page.wait_for_timeout(150)
    check("Active" in page.inner_text("[data-testid=fleet-q-table]"), "Query: job orders with their status")
    page.click("[data-testid=fleet-q-xlsx]")
    page.wait_for_function("() => window.__mock.lastSaved && /fleet-query-jobs.*\\.xlsx$/.test(window.__mock.lastSaved.name)", timeout=10000)
    check(True, "Query → Excel")
    # ---- a period expense
    page.click("[data-testid=fleet-mseg-expenses]"); page.click("[data-testid=fleet-new-expense]"); page.wait_for_selector("[data-testid=fleet-expense-form]")
    page.check("[data-testid=fleet-f-xperiod]"); page.fill("[data-testid=fleet-f-xfrom]", "01/10/2026"); page.fill("[data-testid=fleet-f-xto]", "31/10/2026")
    page.fill("[data-testid=fleet-f-xamount]", "12000"); page.click("[data-testid=fleet-save]"); page.wait_for_timeout(300)
    check("01/10/2026 → 31/10/2026" in page.inner_text("[data-testid=fleet-money]"), "a period expense shows its period")
    # ---- extra fields
    page.click("[data-testid=fleet-tab-fleet]"); page.click("[data-testid=fleet-seg-clients]"); page.locator("[data-testid=fleet-client]").first.click()
    page.wait_for_timeout(200)
    page.click("[data-testid=fleet-tab-fleet]"); page.click("[data-testid=fleet-seg-banks]"); page.click("[data-testid=fleet-add]"); page.wait_for_selector("[data-testid=fleet-list-form]")
    page.fill("[data-testid=fleet-f-name]", "QNB"); page.fill("[data-testid=fleet-f-account]", "1234-5678"); page.click("[data-testid=fleet-save]"); page.wait_for_timeout(300)
    page.locator("[data-testid=fleet-place]", has_text="QNB").click(); page.wait_for_selector("[data-testid=fleet-list-form]")
    check(page.input_value("[data-testid=fleet-f-account]") == "1234-5678", "a bank keeps its account number")
    close(page)
    # ---- Store
    page.click("[data-testid=fleet-tab-store]"); page.click("[data-testid=fleet-sseg-stock]"); page.wait_for_selector("[data-testid=fleet-store-kpis]")
    check("Stock value" in page.inner_text("[data-testid=fleet-store-kpis]"), "the store's dashboard numbers")
    page.click("[data-testid=fleet-sseg-log]"); page.click("[data-testid=fleet-sf-toggle]")
    all_n = page.locator("[data-testid=fleet-tx]").count()
    page.select_option("[data-testid=fleet-sf-tech]", index=1); page.wait_for_timeout(150)
    check(0 < page.locator("[data-testid=fleet-tx]").count() < all_n, "Movements filtered by technician")
    page.click("[data-testid=fleet-sf-clear]"); page.wait_for_timeout(150)
    check(page.locator("[data-testid=fleet-tx]").count() == all_n, "filters cleared")
    page.click("[data-testid=fleet-sseg-reports]"); page.click("[data-testid=fleet-rep-supplier]"); page.locator("[data-testid=fleet-rep-row]").first.click()
    page.wait_for_selector("[data-testid=fleet-history]")
    check(page.locator("[data-testid=fleet-history-table-row]").count() >= 1, "a supplier row opens what it sold us")
    close(page)
    page.click("[data-testid=fleet-rep-ref]"); page.wait_for_timeout(150)
    page.select_option("[data-testid=fleet-ref-pick]", index=0); page.wait_for_timeout(150)
    check(page.locator("[data-testid=fleet-ref-issues]").count() == 1 or "Nothing issued" in page.inner_text("[data-testid=fleet-store]"), "the reference-code report lists what was issued from it")
    page.click("[data-testid=fleet-sseg-lists]"); page.wait_for_selector("[data-testid=fleet-lists]")
    page.locator("[data-testid=fleet-ln-rename]").first.click(); page.fill("[data-testid=fleet-ln-edit]", "Sayed Ali"); page.click("[data-testid=fleet-ln-save]"); page.wait_for_timeout(200)
    check("Sayed Ali" in page.inner_text("[data-testid=fleet-lists]"), "a technician renamed")
    page.click("[data-testid=fleet-sseg-log]"); page.wait_for_timeout(150)
    page.fill("[data-testid=fleet-store-search]", "Sayed Ali"); page.wait_for_timeout(150)
    check(page.locator("[data-testid=fleet-tx]").count() >= 1, "…and every store line follows the new name")
    ctx.close()
    # ---- Arabic
    ctx, page = new_page(br, env, errors, extra_init="try{localStorage.setItem('attune:start','home');localStorage.setItem('attune:ui:lang','ar')}catch(e){};window.__trMiss=new Set()")
    page.set_viewport_size({"width": 390, "height": 844})
    open_fleet(page, "الأعمال")
    page.click("[data-testid=fleet-cash-more]"); page.wait_for_timeout(150)
    page.click("[data-testid=fleet-menu]"); page.click("[data-testid=fleet-rates-open]"); page.wait_for_timeout(150); close(page)
    page.click("[data-testid=fleet-tab-money]"); page.click("[data-testid=fleet-mseg-sites]"); page.wait_for_timeout(150)
    for t in ["cheques", "jobs", "expenses", "moves"]:
        page.click("[data-testid=fleet-mseg-query]"); page.click("[data-testid=fleet-qt-%s]" % t); page.wait_for_timeout(100)
    page.click("[data-testid=fleet-mseg-expenses]"); page.click("[data-testid=fleet-new-expense]"); page.check("[data-testid=fleet-f-xperiod]"); page.wait_for_timeout(100); close(page)
    page.click("[data-testid=fleet-tab-fleet]"); page.click("[data-testid=fleet-seg-banks]"); page.click("[data-testid=fleet-add]"); page.wait_for_timeout(100); close(page)
    page.click("[data-testid=fleet-seg-clients]"); page.click("[data-testid=fleet-add]"); page.wait_for_timeout(100); close(page)
    page.click("[data-testid=fleet-seg-cranes]"); page.click("[data-testid=fleet-add]"); page.wait_for_timeout(100); close(page)
    page.click("[data-testid=fleet-tab-store]"); page.click("[data-testid=fleet-sseg-stock]"); page.click("[data-testid=fleet-sseg-log]"); page.click("[data-testid=fleet-sf-toggle]")
    page.click("[data-testid=fleet-sseg-reports]"); page.click("[data-testid=fleet-rep-ref]"); page.wait_for_timeout(100)
    page.click("[data-testid=fleet-sseg-lists]"); page.wait_for_timeout(150)
    miss = [m for m in page.evaluate("[...window.__trMiss]") if not m.startswith("[DEMO]")]
    check(not miss, "Arabic: no English left on the new screens" + (": " + "; ".join(miss[:12]) if miss else ""))
    check(not real_errors(errors), "no page errors: %s" % real_errors(errors)[:3])
    br.close()
env.close()
finish()
