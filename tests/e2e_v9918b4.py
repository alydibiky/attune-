"""v9.9.19 B4 screens (Ali's picks): T3 countdown chips that open, T2 habits with week dots, T6 full-screen focus timer, T5 week plan.
  PYTHONPATH=tests/pwshim:tests python3 tests/e2e_v9918b4.py
"""
import json, datetime, time
from playwright.sync_api import sync_playwright
from harness import Env, new_page, check, real_errors, finish
env = Env(); errors = []
today = datetime.date.today()
wed = (today + datetime.timedelta(days=39)).isoformat()
INIT = "try{localStorage.setItem('attune:start','home');}catch(e){}"
with sync_playwright() as p:
    br = p.chromium.launch()
    ctx, page = new_page(br, env, errors, legacy_nav=False, extra_init=INIT)
    page.set_viewport_size({"width": 390, "height": 844}); page.goto(env.url); page.wait_for_timeout(1800)
    # ---- T3 countdowns
    check(page.locator("[data-testid=home-countdowns]").count() == 1, "T3: the countdown row is on Home under the box")
    check(page.locator("[data-testid=countdown-chip]").count() == 0, "T3: no chips before any countdown (prayers off → no Ramadan chip)")
    page.locator("[data-testid=countdown-add]").click()
    page.locator("[data-testid=countdown-name]").fill("Wedding")
    page.locator("[data-testid=countdown-when]").fill(wed)
    page.locator("[data-testid=countdown-save]").click(); page.wait_for_timeout(300)
    chip = page.locator("[data-testid=countdown-chip]")
    check(chip.count() == 1 and "Wedding" in chip.inner_text() and "39 days" in chip.inner_text(), "T3: a chip 'Wedding · 39 days': " + (chip.inner_text() if chip.count() else "none"))
    chip.click(); page.wait_for_timeout(200)
    check(page.locator("[data-testid=countdown-days]").inner_text() == "39", "T3: tapping the chip opens the big card with 39")
    page.locator("[data-testid=countdown-edit]").click()
    page.locator("[data-testid=countdown-when]").fill(today.isoformat())
    page.locator("[data-testid=countdown-save]").click(); page.wait_for_timeout(300)
    check("Today" in page.locator("[data-testid=countdown-chip]").inner_text(), "T3: edited to today → 'Today' (the day itself counts as 0)")
    page.locator("[data-testid=countdown-chip]").click(); page.locator("[data-testid=countdown-remove]").click(); page.wait_for_timeout(200)
    check(page.locator("[data-testid=countdown-chip]").count() == 0, "T3: Remove takes it away")
    page.locator("[data-testid=countdown-add]").click(); page.locator("[data-testid=countdown-name]").fill("Old")
    page.locator("[data-testid=countdown-when]").fill((today - datetime.timedelta(days=2)).isoformat())
    check(page.locator("[data-testid=countdown-save]").is_disabled(), "T3: a date in the past can't be saved")
    page.keyboard.press("Escape"); page.mouse.click(5, 5); page.wait_for_timeout(200)
    # ---- T2 habits
    check(page.locator("[data-testid=home-habits]").count() == 0, "T2: no habits card on a calm Home before any habit")
    page.locator("[data-testid=habit-add-chip]").click()
    page.locator("[data-testid=habit-name]").fill("Read 20 pages")
    page.locator("[data-testid=habit-save]").click(); page.wait_for_timeout(300)
    row = page.locator("[data-testid=habit-row]")
    check(row.count() == 1 and "streak 0 days" in row.inner_text(), "T2: the habit shows with streak 0: " + (row.inner_text().replace("\n", " ") if row.count() else "none"))
    check(page.locator("[data-testid=habit-today], [data-testid=habit-dot]").count() == 7, "T2: seven dots for the week")
    page.locator("[data-testid=habit-today]").click(); page.wait_for_timeout(200)
    check("streak 1 day" in row.inner_text() and page.locator("[data-testid=habit-today]").get_attribute("data-s") == "d", "T2: tick today → streak 1 day, today's dot done")
    page.locator("[data-testid=habit-today]").click(); page.wait_for_timeout(200)
    check("streak 0 days" in row.inner_text(), "T2: tap again → unticked (a day counts once)")
    check(page.locator("[data-testid=habit-add-chip]").count() == 0, "T2: the '+ Habit' chip hides once the card has its own")
    # v9.9.38: the week can start on Saturday / Sunday / Monday (country or Settings) — today's dot must still be today, on any day
    for ws in ("6", "0", "1"):
        page.evaluate("localStorage.setItem('attune:week-start', '%s')" % ws); page.reload(); page.wait_for_selector("[data-testid=habit-today]", timeout=10000)
        page.locator("[data-testid=habit-today]").click(); page.wait_for_timeout(200)
        ok = "streak 1 day" in page.locator("[data-testid=habit-row]").inner_text() and page.locator("[data-testid=habit-today]").get_attribute("data-s") == "d"
        i = page.evaluate("[...document.querySelectorAll('[data-testid=habit-today],[data-testid=habit-dot]')].findIndex(e => e.dataset.testid === 'habit-today')")
        check(ok and i == (datetime.date.today().isoweekday() % 7 - int(ws) + 7) % 7, "T2: week starts on day %s → today's dot is in place %s and ticks" % (ws, i))
        page.locator("[data-testid=habit-today]").click(); page.wait_for_timeout(200)
    page.evaluate("localStorage.removeItem('attune:week-start')")
    # ---- T6 focus
    page.evaluate("""() => { localStorage.setItem('attune:focus:run', JSON.stringify({ task: 'Thesis · chapter 3', plan: 25, events: [{ t: Date.now() - 65000, e: 'start' }] })); window.dispatchEvent(new CustomEvent('attune-focus')); }""")
    page.wait_for_timeout(700)
    check(page.locator("[data-testid=focus-screen]").count() == 1 and "Thesis" in page.locator("[data-testid=focus-task]").inner_text(), "T6: the full-screen timer shows the task")
    left = page.locator("[data-testid=focus-left]").text_content()
    check(left.startswith("23:"), "T6: about 23 minutes left after 65 s of a 25-minute plan: " + left)
    page.locator("[data-testid=focus-pause]").click(); page.wait_for_timeout(1300)
    a = page.locator("[data-testid=focus-left]").text_content(); page.wait_for_timeout(1300)
    check(a == page.locator("[data-testid=focus-left]").text_content(), "T6: paused → the time stands still")
    page.locator("[data-testid=focus-stop]").click(); page.wait_for_timeout(300)
    check(page.locator("[data-testid=focus-done]").count() == 1 and "1 m" in page.locator("[data-testid=focus-kept]").inner_text(), "T6: Stop → 'Well done' with 1 m kept")
    saved = page.evaluate("JSON.parse(localStorage.getItem('attune:focus:v1')||'[]')")
    check(len(saved) == 1 and 60000 <= saved[0]["ms"] < 70000, "T6: the session is saved with the focused time only: " + json.dumps(saved))
    page.locator("[data-testid=focus-close]").click()
    # ---- T5 week plan
    now = int(time.time() * 1000)
    page.evaluate("""(n) => { const d = new Date(n + 864e5); d.setHours(10, 0, 0, 0);
      localStorage.setItem('attune:reminders:v1', JSON.stringify([{ id: 'rb', at: d.getTime(), title: 'Site visit', repeat: 'none', created: n, done: false }])); }""", now)
    page.evaluate("window.dispatchEvent(new CustomEvent('attune-weekplan'))"); page.wait_for_timeout(400)
    check(page.locator("[data-testid=weekplan-page]").count() == 1, "T5: the week plan opens")
    page.locator("[data-testid=weekplan-name]").fill("Tender file")
    page.locator("[data-testid=weekplan-hours]").fill("3")
    page.locator("[data-testid=weekplan-due]").fill((today + datetime.timedelta(days=3)).isoformat())
    page.locator("[data-testid=weekplan-add]").click(); page.wait_for_timeout(400)
    check(page.locator("[data-testid=weekplan-plan]").count() >= 1, "T5: Attune's blocks show on the calendar")
    check(page.locator("[data-testid=weekplan-busy]").count() >= 1 and "Site visit" in page.locator("[data-testid=weekplan-busy]").first.inner_text(), "T5: the reminder shows grey as busy")
    page.locator("[data-testid=weekplan-name]").fill("Huge job"); page.locator("[data-testid=weekplan-hours]").fill("200")
    page.locator("[data-testid=weekplan-due]").fill((today + datetime.timedelta(days=1)).isoformat())
    page.locator("[data-testid=weekplan-add]").click(); page.wait_for_timeout(400)
    check(page.locator("[data-testid=weekplan-late]").count() == 1 and "Huge job" in page.locator("[data-testid=weekplan-late]").inner_text(), "T5: a task too big for the time is said, not squeezed")
    page.locator("[data-testid=weekplan-keep]").click(); page.wait_for_timeout(300)
    rem = page.evaluate("JSON.parse(localStorage.getItem('attune:reminders:v1')||'[]')")
    plan = [r for r in rem if r.get("source") == "weekplan"]
    visit = [r for r in rem if r["id"] == "rb"][0]["at"]
    check(len(plan) >= 1 and all(r["title"] == "Tender file" for r in plan), "T5: Keep plan → reminders for the blocks: %d" % len(plan))
    check(all(abs(r["at"] - visit) >= 30 * 60000 for r in plan), "T5: no block starts on the Site visit")
    check(page.locator("[data-testid=weekplan-keep]").is_disabled(), "T5: after keeping, the button says Kept and is off")
    check(len([r for r in page.evaluate("JSON.parse(localStorage.getItem('attune:reminders:v1')||'[]')") if r.get("source") == "weekplan"]) == len(plan), "T5: keeping again never doubles")
    # ---- T4 place inside the reminder
    page.locator("[data-testid=weekplan-back]").click(); page.wait_for_timeout(200)
    ctx.grant_permissions(["geolocation"]); ctx.set_geolocation({"latitude": 29.9601, "longitude": 31.2569})
    page.evaluate("localStorage.setItem('attune:rem:open', JSON.stringify(['fill']))")
    page.evaluate("m => window.dispatchEvent(new CustomEvent('attune-open',{detail:{mode:m}}))", "reminders"); page.wait_for_selector("[data-testid=rem-fill]", timeout=8000)
    page.fill("[data-testid=rem-title]", "Buy milk and bread")
    page.locator("[data-testid=rem-when-place]").click()
    check(page.locator("[data-testid=rem-at]").count() == 0 and page.locator("[data-testid=rem-place]").count() == 1, "T4: 'At a place' swaps the time for the place picker")
    page.fill("[data-testid=rem-place-name]", "Carrefour Maadi"); page.locator("[data-testid=rem-place-here]").click(); page.wait_for_timeout(800)
    places = page.evaluate("JSON.parse(localStorage.getItem('attune:places:v1')||'[]')")
    check(len(places) == 1 and places[0]["name"] == "Carrefour Maadi" and abs(places[0]["lat"] - 29.9601) < 1e-4 and places[0]["r"] == 150, "T4: 'Save where I am' saves the place with its spot: " + json.dumps(places))
    check(page.locator("[data-testid=rem-place-pick]").get_attribute("class").find("c-acc") >= 0, "T4: …and picks it")
    page.locator("[data-testid=rem-place-leave]").click(); page.locator("[data-testid=rem-add]").click(); page.wait_for_timeout(300)
    pr = page.evaluate("JSON.parse(localStorage.getItem('attune:placerem:v1')||'[]')")
    check(len(pr) == 1 and pr[0]["title"] == "Buy milk and bread" and pr[0]["on"] == "leave" and pr[0]["place"] == places[0]["id"], "T4: saved as a place reminder (leave): " + json.dumps(pr))
    it = page.locator("[data-testid=rem-place-item]")
    check(it.count() == 1 and "Carrefour Maadi" in it.inner_text() and "Waiting for the phone part" in it.inner_text(), "T4: listed honestly as waiting for the phone part")
    check(not any(r.get("title") == "Buy milk and bread" for r in page.evaluate("JSON.parse(localStorage.getItem('attune:reminders:v1')||'[]')")), "T4: no fake time reminder made for it")
    # ---- opened from Chat / Tools ("open habits", "open focus"…) — pageOf + navTo
    page.evaluate("m => window.dispatchEvent(new CustomEvent('attune-open',{detail:{mode:m}}))", "focus"); page.wait_for_timeout(400)
    check(page.locator("[data-testid=focus-pick]").count() == 1, "Tools/Chat: 'focus' opens 'Focus on what?'")
    page.fill("[data-testid=focus-what]", "Email the bank"); page.locator("[data-testid=focus-min-15]").click(); page.locator("[data-testid=focus-start]").click(); page.wait_for_timeout(500)
    check(page.locator("[data-testid=focus-screen]").count() == 1 and page.locator("[data-testid=focus-left]").text_content().startswith("1"), "…Start → the timer for 15 minutes")
    page.locator("[data-testid=focus-stop]").click(); page.locator("[data-testid=focus-close]").click()
    page.evaluate("m => window.dispatchEvent(new CustomEvent('attune-open',{detail:{mode:m}}))", "countdowns"); page.wait_for_timeout(800)
    check(page.locator("[data-testid=countdown-form]").count() == 1, "Tools/Chat: 'countdowns' goes Home and opens Add a countdown")
    check(real_errors(errors) == [], "no page errors: " + str(real_errors(errors)[:3]))
    br.close()
env.close(); finish()
