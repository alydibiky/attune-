"""v6.44 Fleet & rentals in depth: an invoice from the work (VAT 14 %), Who owes what (aging), Reports (utilisation, revenue,
fuel), the Team with payroll and an advance, a crane's papers / breakdown / fuel, the new warnings on Today, the settings,
and Arabic (no English left on the new screens).
  PYTHONPATH=tests/pwshim:tests python3 tests/e2e_v744fleetpro.py
"""
import re
from playwright.sync_api import sync_playwright
from harness import Env, new_page, check, real_errors, finish
env = Env(); errors = []
def open_fleet(page):
    page.goto(env.url); page.wait_for_selector("[data-testid=phone-home]", timeout=15000)
    page.locator("nav button").last.click(); page.wait_for_timeout(300)
    page.locator(".rounded-t-2xl button:has-text('Business')").first.click()
    page.wait_for_selector("[data-testid=fleet-open]", timeout=8000); page.click("[data-testid=fleet-open]")
    page.wait_for_selector("[data-testid=fleet-app]", timeout=5000)
with sync_playwright() as p:
    br = p.chromium.launch()
    ctx, page = new_page(br, env, errors, extra_init="try{localStorage.setItem('attune:start','home')}catch(e){}")
    page.set_viewport_size({"width": 390, "height": 844})
    open_fleet(page)
    page.click("[data-testid=fleet-demo]"); page.wait_for_selector("[data-testid=fleet-today]")
    # ---- an invoice from the work
    page.click("[data-testid=fleet-tab-money]"); page.click("[data-testid=fleet-mseg-invoices]")
    page.wait_for_selector("[data-testid=fleet-invoices]")
    check("Not invoiced yet" in page.inner_text("[data-testid=fleet-invoices]"), "Invoices: what is still to collect, overdue, and the work not invoiced yet")
    page.click("[data-testid=fleet-new-invoice]"); page.wait_for_selector("[data-testid=fleet-invoice-form]")
    page.select_option("[data-testid=fleet-f-iclient]", index=1)
    page.wait_for_selector("[data-testid=fleet-invoice-preview]")
    net = page.inner_text("[data-testid=fleet-invoice-net]")
    check("VAT" in page.inner_text("[data-testid=fleet-invoice-preview]") and re.search(r"\d", net), "the preview: the work lines, VAT 14 %, net to pay " + net)
    page.click("[data-testid=fleet-save]"); page.wait_for_selector("[data-testid=fleet-invoice-view]", timeout=4000)
    v = page.inner_text("[data-testid=fleet-invoice-view]")
    check("INV-0001" in v and "Left to pay" in v, "the invoice INV-0001 opens, with what is left to pay")
    page.locator("[data-testid=fleet-sheet] button[aria-label=Close]").click(); page.wait_for_timeout(200)
    check(page.locator("[data-testid=fleet-invoice]").count() >= 1, "it is in the list")
    page.click("[data-testid=fleet-mseg-aging]"); page.wait_for_selector("[data-testid=fleet-aging]")
    check(page.locator("[data-testid=fleet-aging-row]").count() >= 1, "Who owes what: one row per client, by days past due")
    page.click("[data-testid=fleet-mseg-reports]"); page.wait_for_selector("[data-testid=fleet-reports]")
    check(page.locator("[data-testid=fleet-use-row]").count() == 3, "Reports → utilisation: the three cranes")
    page.click("[data-testid=fleet-rseg-revenue]"); page.wait_for_selector("[data-testid=fleet-revenue]")
    check("Total" in page.inner_text("[data-testid=fleet-revenue]"), "revenue per crane per month")
    # ---- the team, payroll, an advance
    page.click("[data-testid=fleet-tab-fleet]"); page.click("[data-testid=fleet-seg-team]"); page.wait_for_selector("[data-testid=fleet-team]")
    page.click("[data-testid=fleet-add]"); page.wait_for_selector("[data-testid=fleet-person-form]")
    page.fill("[data-testid=fleet-f-pname]", "Sayed"); page.select_option("[data-testid=fleet-f-pcrane]", index=1); page.fill("[data-testid=fleet-f-wage]", "500")
    page.click("[data-testid=fleet-save]"); page.wait_for_selector("[data-testid=fleet-payroll]")
    check(page.locator("[data-testid=fleet-person]").count() == 1, "the person is on the Team")
    page.click("[data-testid=fleet-advance]"); page.wait_for_selector("[data-testid=fleet-advance-form]")
    page.fill("[data-testid=fleet-f-adv]", "300"); page.click("[data-testid=fleet-save]"); page.wait_for_timeout(300)
    page.fill("[data-testid=fleet-pay-days]", "20"); page.locator("[data-testid=fleet-pay-days]").blur(); page.wait_for_timeout(300)
    check(page.inner_text("[data-testid=fleet-pay-total]").replace(",", "") == "9700", "payroll: 20 days × 500 − 300 advance = 9,700 (" + page.inner_text("[data-testid=fleet-pay-total]") + ")")
    # ---- a crane's papers, breakdown, fuel
    page.click("[data-testid=fleet-seg-cranes]"); page.locator("[data-testid=fleet-crane]").first.click(); page.wait_for_selector("[data-testid=fleet-crane-detail]")
    page.click("[data-testid=fleet-add-paper]"); page.wait_for_selector("[data-testid=fleet-paper-form]")
    page.select_option("[data-testid=fleet-f-pkind]", "insurance"); page.fill("[data-testid=fleet-f-pexp]", "01/01/2020")
    page.click("[data-testid=fleet-save]"); page.wait_for_selector("[data-testid=fleet-papers]")
    check("Expired" in page.inner_text("[data-testid=fleet-papers]"), "an expired insurance shows red on the crane")
    page.click("[data-testid=fleet-add-repair]"); page.wait_for_selector("[data-testid=fleet-repair-form]")
    page.fill("[data-testid=fleet-f-cause]", "Hydraulic pump"); page.fill("[data-testid=fleet-f-rcost]", "18000"); page.click("[data-testid=fleet-save]")
    page.wait_for_selector("[data-testid=fleet-repairs]")
    check("still down" in page.inner_text("[data-testid=fleet-repairs]") and page.locator("[data-testid=fleet-repair-fixed]").count() == 1, "the breakdown: still down, with 'Fixed today'")
    page.click("[data-testid=fleet-add-fuel]"); page.wait_for_selector("[data-testid=fleet-fuel-form]")
    page.fill("[data-testid=fleet-f-litres]", "120"); page.fill("[data-testid=fleet-f-fcost]", "1800"); page.click("[data-testid=fleet-save]")
    page.wait_for_selector("[data-testid=fleet-fuel]")
    check("120 L" in page.inner_text("[data-testid=fleet-fuel]"), "fuel logged on the crane")
    page.click("[data-testid=fleet-back]"); page.click("[data-testid=fleet-tab-today]"); page.wait_for_selector("[data-testid=fleet-today]")
    t = page.inner_text("[data-testid=fleet-today]")
    check("Insurance expired" in t or "insurance" in t.lower(), "Today warns about the expired insurance")
    check("broken down" in t, "and the crane that is still broken down")
    # ---- settings: company + VAT on invoices
    page.click("[data-testid=fleet-menu]"); page.click("[data-testid=fleet-settings]"); page.wait_for_selector("[data-testid=fleet-settings-form]")
    page.fill("[data-testid=fleet-f-company]", "Adrighem & Aldibiki"); page.click("[data-testid=fleet-save]"); page.wait_for_timeout(300)
    check(page.evaluate("""() => new Promise((ok) => { const r = indexedDB.open('attune-fleet', 1); r.onsuccess = () => { const q = r.result.transaction('kv').objectStore('kv').get('state'); q.onsuccess = () => ok(q.result.settings.company); }; })""") == "Adrighem & Aldibiki", "the company name is saved for the invoices")
    # ---- Arabic: the new screens speak Egyptian Arabic
    ctx.close()
    ctx, page = new_page(br, env, errors, extra_init="try{localStorage.setItem('attune:start','home');localStorage.setItem('attune:ui:lang','ar')}catch(e){};window.__trMiss=new Set()")
    page.set_viewport_size({"width": 390, "height": 844})
    page.goto(env.url); page.wait_for_selector("[data-testid=phone-home]", timeout=15000)
    page.locator("nav button").last.click(); page.wait_for_timeout(300)
    page.locator(".rounded-t-2xl button:has-text('الأعمال')").first.click()
    page.wait_for_selector("[data-testid=fleet-open]", timeout=8000); page.click("[data-testid=fleet-open]")
    page.click("[data-testid=fleet-demo]"); page.wait_for_selector("[data-testid=fleet-today]")
    page.click("[data-testid=fleet-tab-money]")
    for seg in ["invoices", "aging", "reports"]: page.click("[data-testid=fleet-mseg-%s]" % seg); page.wait_for_timeout(200)
    for r in ["revenue", "fuel"]: page.click("[data-testid=fleet-rseg-%s]" % r); page.wait_for_timeout(150)
    page.click("[data-testid=fleet-mseg-invoices]"); page.click("[data-testid=fleet-new-invoice]"); page.select_option("[data-testid=fleet-f-iclient]", index=1); page.wait_for_timeout(200)
    page.click("[data-testid=fleet-save]"); page.wait_for_selector("[data-testid=fleet-invoice-view]", timeout=4000)
    page.locator("[data-testid=fleet-sheet] button[aria-label]").first.click(); page.wait_for_timeout(150)
    page.click("[data-testid=fleet-tab-fleet]"); page.click("[data-testid=fleet-seg-team]"); page.wait_for_timeout(150)
    page.click("[data-testid=fleet-add]"); page.fill("[data-testid=fleet-f-pname]", "سيد"); page.fill("[data-testid=fleet-f-wage]", "500"); page.click("[data-testid=fleet-save]"); page.wait_for_timeout(250)
    page.click("[data-testid=fleet-seg-cranes]"); page.locator("[data-testid=fleet-crane]").first.click(); page.wait_for_timeout(200)
    for k in ["paper", "repair", "fuel"]:
        page.click("[data-testid=fleet-add-%s]" % k); page.wait_for_timeout(150); page.locator("[data-testid=fleet-sheet] button[aria-label]").first.click(); page.wait_for_timeout(100)
    miss = [m for m in page.evaluate("[...window.__trMiss]") if not m.startswith("[DEMO]")]
    check(not miss, "Arabic: no English left on the new screens" + (": " + "; ".join(miss[:8]) if miss else ""))
    check(not real_errors(errors), "no page errors: %s" % real_errors(errors)[:3])
    br.close()
env.close()
finish()
