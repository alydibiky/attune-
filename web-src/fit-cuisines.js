// ---- building the list --------------------------------------------------------------------------------
const MEAL = { b: "breakfast", l: "lunch", d: "dinner", s: "snack" };
const r1 = (v) => Math.round(v * 10) / 10;
const split = (s) => String(s || "").split("|").map((x) => x.trim()).filter(Boolean);
// "Köfte" → also "kofte": people type without the accents (Latin script only — other scripts keep their marks)
const fold = (s) => (/^[\p{Script=Latin}\p{N}\s'’&.,()-]+$/u.test(s) ? s.normalize("NFD").replace(/\p{M}/gu, "").replace(/ı/g, "i").replace(/ß/g, "ss").replace(/[øØ]/g, "o").replace(/[œŒ]/g, "oe") : s);

/** Every dish of every country: { id: "tr.menemen", cc, slug, same (an existing food id, or null), en, local, ar,
 *  aliases: [every other name], serving (g), kcal/p/c/f per 100 g, perServing {kcal,p,c,f}, meals: [...], tags: [...] } */
export const DISHES = [];
for (const [cc, rows] of Object.entries(RAW)) {
  for (const [slugRaw, en, local, ar, serving, kcal, p, c, f, meals, tags] of rows) {
    const [slug, same] = slugRaw.split("=");
    const E = split(en), L = split(local), A = split(ar);
    // "Mathbi (stone-grilled chicken with rice)" is also just "Mathbi"
    const names = [...E, ...E.map((n) => n.replace(/\s*\(.*\)\s*$/, "")), ...L, ...A];
    const aliases = [];
    for (const n of [...names, ...names.map(fold)]) if (n && !aliases.includes(n)) aliases.push(n);
    const k = serving / 100;
    DISHES.push({
      id: cc + "." + slug, cc, slug, same: same || null,
      en: E[0], local: L[0], ar: A[0], aliases: aliases.filter((n) => n !== E[0] && n !== L[0] && n !== A[0]),
      serving, kcal, p, c, f,
      perServing: { kcal: Math.round(kcal * k), p: r1(p * k), c: r1(c * k), f: r1(f * k) },
      meals: [...meals].map((m) => MEAL[m]).filter(Boolean), tags: split(String(tags).replace(/\s+/g, "|")),
    });
  }
}
const BY_CC = new Map();
for (const d of DISHES) { if (!BY_CC.has(d.cc)) BY_CC.set(d.cc, []); BY_CC.get(d.cc).push(d); }

/** The dishes of one country (in the order above: the most typical first). */
export const dishesOf = (cc) => BY_CC.get(cc) || [];
export const countryName = (cc, ar) => (COUNTRIES[cc] ? (ar ? COUNTRIES[cc].ar : COUNTRIES[cc].en) : "");

/**
 * A flat list for a fast on-device photo matcher's name bank: one row per name (English, local script, Arabic,
 * aliases) → [{ id, foodId, cc, name, lang: "en" | "local" | "ar" | "alias" }]. foodId is the food-table id the
 * dish is logged as (an existing food for "same" dishes).
 */
export function allDishNames() {
  const out = [];
  for (const d of DISHES) {
    const foodId = d.same || d.id;
    const seen = new Set();
    const put = (name, lang) => { if (name && !seen.has(name)) { seen.add(name); out.push({ id: d.id, foodId, cc: d.cc, name, lang }); } };
    put(d.en, "en"); put(d.local, "local"); put(d.ar, "ar");
    for (const a of d.aliases) put(a, "alias");
  }
  return out;
}

